import hashlib
import json
import re
import uuid
from dataclasses import dataclass
from datetime import timezone as datetime_timezone
from typing import Any

from django.db import DatabaseError, transaction
from django.utils import timezone

from .constants import (
    ALLOWED_AUDIT_METADATA_KEYS,
    AUDIT_EVENT_SCHEMA_VERSION,
    GENESIS_HASH,
    AuditAction,
    AuditCategory,
    AuditOrigin,
    AuditOutcome,
)
from .exceptions import AuditValidationError, AuditWriteError
from .models import GovernanceAuditChain, GovernanceAuditEvent


MAX_METADATA_KEYS = 16
MAX_METADATA_STRING = 256
MAX_METADATA_LIST = 20
MAX_METADATA_BYTES = 4096
CONTROLLED_IDENTIFIER = re.compile(r"^[A-Z][A-Z0-9_]{0,63}$")
SECRET_ASSIGNMENT = re.compile(
    r"(?i)\b(password|activation[_ -]?token|session(?:id)?|csrf(?:token)?|database_url|django_secret_key|authorization)\b\s*[:=]\s*[^\s,;]+"
)


def new_correlation_id() -> uuid.UUID:
    return uuid.uuid4()


def _normalize_correlation_id(value: uuid.UUID | str | None) -> uuid.UUID:
    if value is None:
        return new_correlation_id()
    if isinstance(value, uuid.UUID):
        return value
    try:
        return uuid.UUID(str(value))
    except (TypeError, ValueError, AttributeError) as exc:
        raise AuditValidationError("Correlation ID must be a UUID generated by the server.") from exc


def _sanitize_metadata_value(value: Any) -> Any:
    if value is None or isinstance(value, (bool, int, float)):
        return value
    if isinstance(value, str):
        if len(value) > MAX_METADATA_STRING:
            raise AuditValidationError("Audit metadata strings are limited to 256 characters.")
        if SECRET_ASSIGNMENT.search(value):
            raise AuditValidationError("Secret-shaped values are not allowed in audit metadata.")
        return value
    if isinstance(value, (list, tuple)):
        if len(value) > MAX_METADATA_LIST:
            raise AuditValidationError("Audit metadata lists are limited to 20 values.")
        if any(isinstance(item, (dict, list, tuple)) for item in value):
            raise AuditValidationError("Nested audit metadata structures are not allowed.")
        return [_sanitize_metadata_value(item) for item in value]
    raise AuditValidationError("Audit metadata supports only bounded primitive values and primitive lists.")


def sanitize_metadata(metadata: dict[str, Any] | None) -> dict[str, Any]:
    if metadata is None:
        return {}
    if not isinstance(metadata, dict):
        raise AuditValidationError("Audit metadata must be an object.")
    if len(metadata) > MAX_METADATA_KEYS:
        raise AuditValidationError("Audit metadata contains too many keys.")
    sanitized: dict[str, Any] = {}
    for key in sorted(metadata):
        if key not in ALLOWED_AUDIT_METADATA_KEYS:
            raise AuditValidationError(f"Audit metadata key is not allowed: {key}")
        sanitized[key] = _sanitize_metadata_value(metadata[key])
    encoded = json.dumps(sanitized, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")
    if len(encoded) > MAX_METADATA_BYTES:
        raise AuditValidationError("Audit metadata exceeds the 4096-byte limit.")
    return sanitized


def _timestamp(value) -> str:
    if timezone.is_naive(value):
        raise AuditValidationError("Audit timestamps must be timezone-aware.")
    return value.astimezone(datetime_timezone.utc).isoformat(timespec="microseconds").replace("+00:00", "Z")


def canonical_event_payload(values: dict[str, Any]) -> bytes:
    payload = {
        "action": values["action"],
        "actor_role_snapshot": values["actor_role_snapshot"],
        "actor_user_id": values["actor_user_id"],
        "category": values["category"],
        "correlation_id": str(values["correlation_id"]),
        "metadata": values["metadata"],
        "new_state": values["new_state"],
        "occurred_at": _timestamp(values["occurred_at"]),
        "organization_id_snapshot": values["organization_id_snapshot"],
        "origin": values["origin"],
        "outcome": values["outcome"],
        "previous_hash": values["previous_hash"],
        "previous_state": values["previous_state"],
        "reason": values["reason"],
        "reason_code": values["reason_code"],
        "resource_id": values["resource_id"],
        "resource_type": values["resource_type"],
        "resource_version": values["resource_version"],
        "schema_version": values["schema_version"],
        "sequence": values["sequence"],
        "source_identifier": values["source_identifier"],
        "source_occurred_at": _timestamp(values["source_occurred_at"]) if values["source_occurred_at"] else None,
    }
    return json.dumps(payload, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")


def _event_values(event: GovernanceAuditEvent) -> dict[str, Any]:
    return {field: getattr(event, field) for field in (
        "sequence", "schema_version", "occurred_at", "category", "action", "outcome",
        "actor_user_id", "actor_role_snapshot", "organization_id_snapshot", "resource_type",
        "resource_id", "resource_version", "correlation_id", "reason_code", "reason",
        "previous_state", "new_state", "metadata", "previous_hash", "origin",
        "source_identifier", "source_occurred_at",
    )}


def record_governance_event(
    *,
    category: str,
    action: str,
    outcome: str,
    resource_type: str,
    resource_id: str,
    actor=None,
    actor_role: str = "",
    organization_id: int | None = None,
    resource_version: int | None = None,
    correlation_id: uuid.UUID | str | None = None,
    reason_code: str = "",
    reason: str = "",
    previous_state: str = "",
    new_state: str = "",
    metadata: dict[str, Any] | None = None,
    origin: str = AuditOrigin.LIVE,
    source_identifier: str | None = None,
    source_occurred_at=None,
    occurred_at=None,
) -> GovernanceAuditEvent:
    if category not in AuditCategory.values or action not in AuditAction.values or outcome not in AuditOutcome.values:
        raise AuditValidationError("Audit category, action, and outcome must use controlled constants.")
    if origin not in AuditOrigin.values:
        raise AuditValidationError("Audit origin must use a controlled constant.")
    if not resource_type or len(resource_type) > 64 or not resource_id or len(str(resource_id)) > 128:
        raise AuditValidationError("Audit resource identifiers are missing or too long.")
    if actor_role and not CONTROLLED_IDENTIFIER.fullmatch(actor_role):
        raise AuditValidationError("Actor role snapshots must be controlled machine identifiers.")
    if reason_code and not CONTROLLED_IDENTIFIER.fullmatch(reason_code):
        raise AuditValidationError("Reason codes must be controlled machine identifiers.")
    clean_reason = SECRET_ASSIGNMENT.sub(lambda match: f"{match.group(1)}=[REDACTED]", reason.strip())
    if len(clean_reason) > 1000:
        raise AuditValidationError("Audit reasons are limited to 1000 characters.")
    clean_metadata = sanitize_metadata(metadata)
    event_time = occurred_at or timezone.now()
    correlation = _normalize_correlation_id(correlation_id)

    try:
        with transaction.atomic():
            chain = GovernanceAuditChain.objects.select_for_update().get(pk=1)
            values = {
                "sequence": chain.last_sequence + 1,
                "schema_version": AUDIT_EVENT_SCHEMA_VERSION,
                "occurred_at": event_time,
                "category": category,
                "action": action,
                "outcome": outcome,
                "actor_user_id": getattr(actor, "pk", None),
                "actor_role_snapshot": actor_role,
                "organization_id_snapshot": organization_id,
                "resource_type": resource_type,
                "resource_id": str(resource_id),
                "resource_version": resource_version,
                "correlation_id": correlation,
                "reason_code": reason_code,
                "reason": clean_reason,
                "previous_state": previous_state,
                "new_state": new_state,
                "metadata": clean_metadata,
                "previous_hash": chain.head_hash,
                "origin": origin,
                "source_identifier": source_identifier,
                "source_occurred_at": source_occurred_at,
            }
            event_hash = hashlib.sha256(canonical_event_payload(values)).hexdigest()
            event = GovernanceAuditEvent(**values, event_hash=event_hash)
            event._audit_insert_allowed = True
            event.save(force_insert=True)
            chain.last_sequence = values["sequence"]
            chain.head_hash = event_hash
            chain.save(update_fields=("last_sequence", "head_hash", "updated_at"))
            return event
    except AuditValidationError:
        raise
    except (DatabaseError, GovernanceAuditChain.DoesNotExist) as exc:
        raise AuditWriteError("The governance audit event could not be recorded.") from exc


@dataclass(frozen=True)
class AuditVerificationResult:
    valid: bool
    events_checked: int
    first_sequence: int | None
    last_sequence: int | None
    head_hash: str
    first_broken_sequence: int | None = None
    reason: str = ""


def verify_audit_chain() -> AuditVerificationResult:
    try:
        chain = GovernanceAuditChain.objects.get(pk=1)
    except GovernanceAuditChain.DoesNotExist:
        return AuditVerificationResult(False, 0, None, None, "", 1, "CHAIN_HEAD_MISSING")
    previous_hash = GENESIS_HASH
    expected_sequence = 1
    checked = 0
    first_sequence = None
    last_sequence = None
    for event in GovernanceAuditEvent.objects.order_by("sequence").iterator(chunk_size=500):
        first_sequence = first_sequence or event.sequence
        if event.sequence != expected_sequence:
            return AuditVerificationResult(False, checked, first_sequence, last_sequence, chain.head_hash, expected_sequence, "SEQUENCE_GAP")
        if event.previous_hash != previous_hash:
            return AuditVerificationResult(False, checked, first_sequence, last_sequence, chain.head_hash, event.sequence, "PREVIOUS_HASH_MISMATCH")
        recomputed = hashlib.sha256(canonical_event_payload(_event_values(event))).hexdigest()
        if event.event_hash != recomputed:
            return AuditVerificationResult(False, checked, first_sequence, last_sequence, chain.head_hash, event.sequence, "EVENT_HASH_MISMATCH")
        previous_hash = event.event_hash
        last_sequence = event.sequence
        expected_sequence += 1
        checked += 1
    expected_last = last_sequence or 0
    if chain.last_sequence != expected_last:
        return AuditVerificationResult(False, checked, first_sequence, last_sequence, chain.head_hash, expected_sequence, "CHAIN_HEAD_SEQUENCE_MISMATCH")
    if chain.head_hash != previous_hash:
        return AuditVerificationResult(False, checked, first_sequence, last_sequence, chain.head_hash, expected_sequence, "CHAIN_HEAD_HASH_MISMATCH")
    return AuditVerificationResult(True, checked, first_sequence, last_sequence, chain.head_hash)


def audit_health() -> dict[str, Any]:
    chain = GovernanceAuditChain.objects.get(pk=1)
    last_event = GovernanceAuditEvent.objects.order_by("-sequence").only("sequence", "event_hash", "occurred_at").first()
    count = GovernanceAuditEvent.objects.count()
    consistent = (
        (last_event is None and chain.last_sequence == 0 and chain.head_hash == GENESIS_HASH)
        or (
            last_event is not None
            and chain.last_sequence == last_event.sequence
            and chain.head_hash == last_event.event_hash
            and count == chain.last_sequence
        )
    )
    return {
        "event_count": count,
        "last_sequence": chain.last_sequence,
        "last_event_time": last_event.occurred_at.isoformat() if last_event else None,
        "chain_head_consistent": consistent,
    }
